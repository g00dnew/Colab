    ho_voc_bor = ho[~ho.own_input_layer & (ho.modality == "vocal")]
    ho_nonvoc = ho[~ho.own_input_layer & (ho.modality == "nonvocal")]

    def wper(x):
        return 100 * x.edit_distance.sum() / x.n_phonemes_true.sum() if len(x) else float("nan")

