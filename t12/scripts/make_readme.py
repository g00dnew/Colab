def versions():
    try:
        txt = subprocess.run([str(VENV), "-m", "pip", "freeze"], capture_output=True,
                             text=True, timeout=120).stdout
    except Exception:
        return "    (pip freeze unavailable)"
    have = {}
    for line in txt.splitlines():
        if "==" in line:
            k, v = line.split("==", 1)
            have[k.lower()] = v
    rows = [f"| {p} | {have.get(p.lower(), '-')} |" for p in PKGS]
    return "\n".join(rows)


def per_table(g):
    cols = ["session", "partition", "modality", "input_layer_from", "own_input_layer",
            "held_out", "n_trials", "n_aligned", "n_phonemes_true", "per"]
    g = g[cols].copy()
    g["per"] = (g["per"] * 100).round(2)
    g = g.rename(columns={"per": "PER_%", "own_input_layer": "own_layer"})
    head = "| " + " | ".join(g.columns) + " |"
    sep = "|" + "---|" * len(g.columns)
    body = "\n".join("| " + " | ".join(str(x) for x in r) + " |"
                     for r in g.itertuples(index=False))
    return "\n".join([head, sep, body])


